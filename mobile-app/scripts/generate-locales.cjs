function mapValues(keys, values) {
  if (keys.length !== values.length) {
    throw new Error("Translation count mismatch");
  }

  return Object.fromEntries(
    keys.map((key, index) => [key, values[index]])
  );
}

function saveLocale(code, data) {
  fs.writeFileSync(
    path.join(directory, `${code}.json`),
    JSON.stringify(data, null, 2) + "\n",
    "utf8"
  );

  console.log(`Generated: ${code}.json`);
}

saveLocale("en", en);
saveLocale("te", te);

for (const [code, data] of Object.entries(translations)) {
  const locale = {
    common: mapValues(commonKeys, data.common),

    language: mapValues(languageKeys, data.language),

    onboarding: {
      progress: data.progress,
      titles: data.titles,
      subtitles: data.subtitles,
      ...mapValues(onboardingKeys, data.onboarding)
    },

    activities: mapValues(activityKeys, data.activities),

    features: Object.fromEntries(
      featureKeys.map((key, index) => [
        key,
        {
          title: data.features[index][0],
          description: data.features[index][1]
        }
      ])
    ),

    tabs: mapValues(tabKeys, data.tabs)
  };

  saveLocale(code, locale);
}

